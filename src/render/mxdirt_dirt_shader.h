#ifndef MXDIRT_DIRT_SHADER_H
#define MXDIRT_DIRT_SHADER_H
/* Dirt Material shader. Composes against ONE snapshot of the native ground
   colour, so each track keeps its own authored dirt colour and texture. Only
   shading and soil state change:
   - per-pixel normals from the full-resolution height grid (crisper rut walls
     than the native per-vertex/LOD normals; half-cell differences),
   - generated micro-relief in world metres (the clod texture is generated by
     mxdirt_clods(), no imported textures), relit against the native sun.
     Untouched ground stays exactly native; clods and crumbs appear only where
     riding raised, dug or tore the ground,
   - cavity darkening in hollows and a slight rim lift on disturbed edges,
   - soil state from the dirt sim's per-texel state (packed / loose / wetness /
     roost clods, same grid as the heights); without it, from CURRENT minus BASE
     height alone (raised/torn reads loose, smooth dug lines read packed),
   - sun shadows cast by the deformation only (native hills keep the game's
     own shadows), knob bars and drag streaks along each rut's travel axis, a
     faint sheen on hard-pack and wet rut bottoms,
   - worked ground is resurfaced: the native texture's own gravel grain is
     averaged over ~2 cm of ground and replaced by soft clods and crumbs that
     fade with pixel size instead of sparkling.
   (Tyre marks are the soft top layer's: trenches with knob pits. The separate
   print band drawn from the sim's print arrays was removed in 1.5.1 - it cost
   frame time and could not be told apart from the soft layer's own marks.)
   Green (grass) pixels are mostly left alone. Fades out by dirt_fade_start..
   dirt_fade_end and at the window edge. Depth/alpha are never written. */
static const char mxdirt_vertex_shader[]=
 "#version 330 compatibility\n"
 "layout(location=0) in vec2 cell;"
 "uniform sampler2D heights;uniform mat4 view,projection;uniform vec3 texel0,camera;uniform vec2 spacing;uniform float height_scale;"
 "out vec2 gv;out vec3 wv;"
 "void main(){ivec2 t=ivec2(cell)+ivec2(2);float h=texelFetch(heights,t,0).r*height_scale;"
 "vec3 p=vec3(texel0.x+float(t.x)*spacing.x,texel0.y+h,texel0.z+float(t.y)*spacing.y);"
 "p.y+=.004+.001*distance(p,camera);gv=vec2(t)+.5;wv=p;gl_Position=projection*view*vec4(p,1);}";
static const char mxdirt_fragment_shader[]=
 "#version 330 compatibility\n"
 "uniform sampler2D heights,background,clods;uniform ivec2 viewport_origin;uniform mat4 view,projection;uniform vec3 texel0;"
 "uniform vec2 spacing,fade;uniform vec4 bounds;uniform vec3 camera;uniform float height_scale,strength,base_grain;"
 "uniform sampler2D state;uniform int state_on;"
 "uniform sampler2D soft;uniform int soft_on,soft_mode;uniform vec2 soft_origin;uniform vec4 soft_window;uniform float soft_cell,soft_depth,soft_unit;"
 "in vec2 gv;in vec3 wv;layout(location=0) out vec4 color;"
 "const float SIDE=261.;"
 "vec2 H(vec2 c){return texture(heights,c/SIDE).rg*height_scale;}"
 /* soft top layer height (m, relative to the untouched layer top) at a local point; the window wraps every 2048 texels */
 "float SH(vec2 l){return (texture(soft,l/(soft_cell*2048.)).r*255.-128.)*soft_unit;}"
 /* knob blocks of a tread pressed along f: rows every 5.2 cm, 3 cm blocks across, staggered */
 "float kblock(vec2 q,vec2 f,vec2 n){float b=floor(dot(q,n)/.03),s=dot(q,f)/.052+.5*mod(b,2.),c=fract(dot(q,n)/.03);"
 "return smoothstep(.3,.18,abs(fract(s)-.5))*smoothstep(.47,.36,abs(c-.5));}"
 "vec2 turn(vec2 v,float a){float c=cos(a),s=sin(a);return vec2(c*v.x-s*v.y,s*v.x+c*v.y);}"
 /* integer hash -> 3 uniform values per lattice cell (stable in world space) */
 "vec3 rnd(vec2 id){uvec2 q=uvec2(ivec2(id)+ivec2(1048576));uint h=(q.x*1597334677u)^(q.y*3812015801u);h^=h>>16;h*=2246822519u;h^=h>>13;h*=3266489917u;h^=h>>16;"
 "return vec3(uvec3(h,h>>11,h>>22)&uvec3(2047u,2047u,1023u))/vec3(2047.,2047.,1023.);}"
 "void main(){vec2 g=gv;vec3 w=wv;gl_FragDepth=gl_FragCoord.z;"
 /* metres of ground per pixel: every procedural layer fades out before it aliases */
 "vec2 p=w.xz,dpx=dFdx(p),dpy=dFdy(p);float px=max(length(dpx),length(dpy));"
 "float dist=distance(w,camera);"
 "float edge=min(min(w.x-bounds.x,bounds.z-w.x),min(w.z-bounds.y,bounds.w-w.z));"
 "float amount=(1.-smoothstep(fade.x,fade.y,dist))*smoothstep(0.,3.,edge)*strength;"
 "if(amount<=.003)discard;"
 "ivec2 pix=ivec2(gl_FragCoord.xy)-viewport_origin;"
 /* Soft top layer, first: the view ray is marched down through it (parallax). The layer lies ON the ridden
    ground: its untouched top sits so above the terrain mesh, so a pressed trench floor (~.6 of the layer)
    is where the bike's tyre actually rolls.
    soft_mode bit 0 - solid layer: the soil the ray hits belongs to the ground point under it, a little
    toward the camera, so everything from here on (the native ground texture, the height field, the sim
    state) is taken at THAT ground point. The relief then carries the ground with it like real
    displaced dirt; lit on the texture of the mesh point behind it, it read as a translucent sheet floating
    over the ground.
    soft_mode bit 2 - depth-only draw: only where the layer stands above the mesh, at the depth of its
    surface, so the bike drawn afterwards sinks into the loose soil instead of standing on top of it. */
 "float s_vis=0.,s_up=0.;vec2 s_q=vec2(0.);"
 "if(soft_on!=0){vec2 sl=p-soft_origin;float se=min(min(sl.x-soft_window.x,soft_window.z-sl.x),min(sl.y-soft_window.y,soft_window.w-sl.y));"
 "s_vis=smoothstep(.5,3.,se)*(1.-smoothstep(soft_cell*1.2,soft_cell*5.,px));s_q=sl;"
 "if(s_vis>.01){vec3 Vs=normalize(camera-w);vec2 dv=Vs.xz/max(Vs.y,.2);float so=.6*soft_depth,top=so+min(127.*soft_unit,soft_depth*1.7),bot=so-min(127.*soft_unit,soft_depth*2.);"
 "float yp=top,hp=SH(sl+dv*top)+so,yh=bot;"
 "for(int i=1;i<=16;i++){float y=mix(top,bot,float(i)/16.),h=SH(sl+dv*y)+so;if(h>=y){float t=(yp-hp)/max((yp-hp)-(y-h),1e-6);yh=mix(yp,y,clamp(t,0.,1.));break;}yp=y;hp=h;}"
 "s_up=yh*s_vis;vec2 sh=dv*s_up;s_q=sl+sh;"
 "if((soft_mode&4)!=0){if(s_up<.004)discard;vec4 c=projection*view*vec4(w+Vs*(s_up/max(Vs.y,.2)),1.);gl_FragDepth=clamp(c.z/max(c.w,1e-4)*.5+.5,0.,1.);color=vec4(0.);return;}"
 "if((soft_mode&1)!=0){g+=sh/spacing;w.xz+=sh;p=w.xz;"
 "float hy=texture(heights,g/SIDE).r*height_scale;vec4 c=projection*view*vec4(p.x,texel0.y+hy+.004,p.y,1.);"
 "if(c.w>.05){vec2 n=c.xy/c.w;if(abs(n.x)<.999&&abs(n.y)<.999)pix=ivec2((n*.5+.5)*vec2(textureSize(background,0)));}}}}"
 "if((soft_mode&4)!=0)discard;"
 "vec3 native=texelFetch(background,pix,0).rgb;"
 "float lum0=dot(native,vec3(.299,.587,.114));"
 "float green=clamp((native.g-max(native.r,native.b))/max(lum0,.02)*4.,0.,1.);"
 /* native sun, eye space -> world via the captured terrain view */
 "vec3 L=transpose(mat3(view))*gl_LightSource[0].position.xyz;"
 "L=length(L)>1e-4?normalize(L):vec3(.39,.82,.42);if(L.y<.08)L=normalize(vec3(L.x,.08,L.z));"
 /* height field: centre, +-1 and +-.5 cell, a ~2 cell ring */
 "vec2 c0=H(g),xp=H(g+vec2(1,0)),xm=H(g-vec2(1,0)),zp=H(g+vec2(0,1)),zm=H(g-vec2(0,1));"
 "vec2 base_slope=vec2(xp.r-xm.r,zp.r-zm.r)/(2.*spacing);"
 "vec2 hx=H(g+vec2(.5,0))-H(g-vec2(.5,0)),hz=H(g+vec2(0,.5))-H(g-vec2(0,.5));"
 "vec2 sharp_slope=mix(base_slope,vec2(hx.r,hz.r)/spacing,.45);"
 "vec2 dslope=vec2(hx.r-hx.g,hz.r-hz.g)/spacing;"
 /* shallow wear (ruts ~4-6 cm, rows ~8 cm) is lit ~30 % steeper than it is so it
    reads at riding distance (light only, the ridden ground is unchanged) */
 "float wall=smoothstep(.25,.8,length(dslope));"
 "vec2 ring=(H(g+vec2(2,0))+H(g-vec2(2,0))+H(g+vec2(0,2))+H(g-vec2(0,2))+H(g+vec2(1.4,1.4))+H(g-vec2(1.4,1.4))+H(g+vec2(1.4,-1.4))+H(g-vec2(1.4,-1.4)))*.125;"
 /* hollow: of the deformation alone (+ in ruts/hollows, - on crests and lips) */
 "float dd=c0.r-c0.g,hollow=(ring.r-ring.g)-dd;"
 "float dlap=(xp.r-xp.g)+(xm.r-xm.g)+(zp.r-zp.g)+(zm.r-zm.g)-4.*dd;"
 "float raised=smoothstep(.004,.04,dd),dug=smoothstep(.004,.05,-dd),rough=smoothstep(.012,.06,abs(dlap));"
 /* soil state: the dirt sim's own per-texel state, else height-only defaults */
 "float s_pack=0.,s_loose=0.,wet=.35,s_clod=0.;"
 "if(state_on!=0){vec4 q=texture(state,g/SIDE);s_pack=q.r;s_loose=q.g;wet=q.b;s_clod=q.a;}"
 "float scuff=smoothstep(.0008,.006,abs(dd))*(1.-smoothstep(.008,.025,abs(dd)));"
 /* with the sim state the mm-scale scuff fringe is not needed to find worked
    ground; keeping it small keeps rut edges crisp instead of fuzzy */
 "float worked=clamp(max(max(raised,dug),max(rough,1.6*max(s_pack,s_loose)))+(state_on!=0?.15:.5)*scuff,0.,1.);"
 "float loose=clamp(max(s_loose,max(.6*rough,.25*raised))*worked,0.,1.);"
 "float firm=clamp(max(s_pack,.6*dug*(1.-rough)*(1.-wall)),0.,1.)*(1.-.7*loose);"
 /* raised convex lips crumble (relief only) */
 "float lumpy=max(loose,.8*raised*smoothstep(.01,.05,-hollow)*(1.-firm));"
 /* moisture: rut bottoms and hollows stay damp, crests dry out first */
 "float cav=clamp(hollow*14.,-1.,1.),damp=smoothstep(.30,.62,wet);"
 "float wetv=worked*damp*clamp(.30+.45*cav+.45*dug,0.,1.)*(1.-.5*loose);"
 "float dryv=worked*(1.-damp)*clamp(.30-.6*cav+.3*raised,0.,1.);"
 /* resurface worked ground: the native texture's own gravel grain averaged over a
    2 cm ring ON THE GROUND (world offsets mapped to pixels through the inverse
    pixel footprint, so grazing views never smear along the view direction) */
 "ivec2 vmax=textureSize(background,0)-1;vec3 blur=native;float bw=1.,det=dpx.x*dpy.y-dpy.x*dpx.y;"
 /* perf: the 2 cm ring is under ~1 pixel beyond px 5 cm, and nothing uses it on untouched ground without the soft layer */
 "if(abs(det)>1e-14&&px<.05&&(worked>.003||soft_on!=0)){mat2 Ji=mat2(dpy.y,-dpx.y,-dpy.x,dpx.x)/det;"
 "for(int i=0;i<6;i++){float a=1.0472*float(i)+.5236;vec2 o=Ji*(vec2(cos(a),sin(a))*.02);float ol=length(o);if(ol>10.)o*=10./ol;"
 "blur+=texelFetch(background,clamp(pix+ivec2(round(o)),ivec2(0),vmax),0).rgb;bw+=1.;}}"
 "vec3 albedo=mix(native,blur/bw,worked*(.12+.28*firm));" /* loose dirt keeps its grit, packed lines smooth out */
 /* clods (~4-6 cm) on loose soil, crumbs (~2 cm) on worked soil, soft swell (~20 cm) */
 "float f_big=1.-smoothstep(.010,.025,px),f_mid=1.-smoothstep(.004,.010,px);"
 "vec4 k1=texture(clods,p/.45),k2=texture(clods,turn(p,.83)/.31+vec2(.37,.11)),k3=texture(clods,turn(p,1.9)/1.3+vec2(.71,.29));"
 "float a_clod=lumpy*f_big,a_crumb=worked*(.30+.35*(1.-firm))*f_mid,a_soft=worked*(.25+.5*loose)*f_big;"
 "vec2 micro=(k1.rg-.5)*2.*.42*a_clod+turn((k2.rg-.5)*2.,-.83)*.30*a_crumb+turn((k3.rg-.5)*2.,-1.9)*.30*a_soft;"
 "float crevice=1.-.16*a_clod*(.5-k1.b)-.08*a_crumb*(.5-k2.b);" /* centred: relief, not a net darkening */
 /* fine grain (dirt_loose) and clumps: two more rotated, offset samples of the same
    generated clod relief at ~19 cm and ~62 cm repeats, worked ground only */
 "vec4 k4=texture(clods,turn(p,2.4)/.19+vec2(.23,.61)),k5=texture(clods,turn(p,.4)/.62+vec2(.47,.83));"
 "float wf=worked*base_grain*(1.-.6*firm)*f_mid,wc=lumpy*f_big;"
 "micro+=turn((k4.rg-.5)*2.,-2.4)*.24*wf+turn((k5.rg-.5)*2.,-.4)*.22*wc;"
 "crevice*=1.+.06*wc*(k5.b-.5);"
 /* tread: travel axis = low-curvature axis of the dug delta's Hessian, so knob
    bars run across each rut and drag streaks along it; crisp in damp soil */
 "vec2 d11=H(g+vec2(1,1)),dmm=H(g-vec2(1,1)),d1m=H(g+vec2(1,-1)),dm1=H(g+vec2(-1,1));"
 "float hxx=((xp.r-xp.g)+(xm.r-xm.g)-2.*dd)/(spacing.x*spacing.x),hzz=((zp.r-zp.g)+(zm.r-zm.g)-2.*dd)/(spacing.y*spacing.y);"
 "float hxz=((d11.r-d11.g)+(dmm.r-dmm.g)-(d1m.r-d1m.g)-(dm1.r-dm1.g))/(4.*spacing.x*spacing.y);"
 "float hd=.5*(hxx-hzz),hr=sqrt(hd*hd+hxz*hxz),hm=.5*(hxx+hzz);"
 "float anis=clamp(2.*hr/(abs(hm+hr)+abs(hm-hr)+1e-3),0.,1.);"
 "float th=hr>1e-6?.5*atan(hxz,hd):0.;vec2 across=vec2(cos(th),sin(th)),along=vec2(-across.y,across.x);"
 "float tw=dug*anis*smoothstep(.05,.4,hr)*(1.-.65*loose)*(.35+.65*damp);"
 "float s=dot(p,along)/.075+.6*k2.b,fs=(abs(dot(dpx,along))+abs(dot(dpy,along)))/.075;"
 "float knob=smoothstep(.35,.6,k1.g)*(1.-smoothstep(.2,.45,fs));"
 "float st=dot(p,across)/.3,fst=(abs(dot(dpx,across))+abs(dot(dpy,across)))/.3;vec2 su=vec2(st,dot(p,along)/5.);"
 "float streak=(texture(clods,su+vec2(.02,0)).r-texture(clods,su-vec2(.02,0)).r)*(1.-smoothstep(.15,.4,8.*fst));"
 "micro+=(along*(cos(6.2832*s)*.22*knob)+across*(streak*.9))*tw;"
 /* soft top layer (core: mxdirt_soft_layer.h): loose soil lying on the dirt. Near
    the camera the view ray is marched down through it (parallax), so trenches
    read deep and lips stand up; lit from its own slopes and shadowed by them.
    Untouched layer: the native gravel grain softened into fine loose crumbs. */
 "float s_h=0.,s_press=0.,s_lip=0.,s_shade=1.,s_cav=0.,s_lay=0.,s_new=0.;"
 "if(soft_on!=0){s_lay=1.-green;"
 "if(s_vis>.01){"
 "vec2 q=s_q;float c=soft_cell;s_h=SH(q);"
 "vec2 sg=vec2(SH(q+vec2(c,0))-SH(q-vec2(c,0)),SH(q+vec2(0,c))-SH(q-vec2(0,c)))/(2.*c);"
 "s_cav=(SH(q+vec2(2.5*c,0))+SH(q-vec2(2.5*c,0))+SH(q+vec2(0,2.5*c))+SH(q-vec2(0,2.5*c)))*.25-s_h;"
 "if(L.y<.97){vec2 sd=L.xz/max(L.y,.12);float occ=0.;"
 "for(int i=1;i<=8;i++){float d=.011*float(i);occ=max(occ,clamp((SH(q+sd*d)-s_h-d)/.005,0.,1.)*(1.-float(i)/10.));}s_shade=1.-.42*occ;}"
 "s_press=smoothstep(.2,.65,-s_h/soft_depth);s_lip=smoothstep(.001,.007,s_h);"
 /* fresh tread: knob blocks pressed into the trench floor along the last tyre's travel */
 "float tg=texelFetch(soft,ivec2(floor(q/c))&ivec2(2047),0).g*255.;vec2 kg=vec2(0);"
 /* freshness 0..1 of the soil here (bilinear over the four nearest texels' 2-bit age) */
 "{vec2 fq=q/c-.5;ivec2 f0=ivec2(floor(fq));vec2 ff=fq-vec2(f0);float a4[4];"
 "for(int i=0;i<4;i++)a4[i]=floor(mod(texelFetch(soft,(f0+ivec2(i&1,i>>1))&ivec2(2047),0).g*255.+.5,128.)/32.);"
 "s_new=mix(mix(a4[0],a4[1],ff.x),mix(a4[2],a4[3],ff.x),ff.y)/3.;}"
 "if(tg>127.5&&s_press>.05){float a=mod(tg+.5,32.)/32.*3.14159265;vec2 f=vec2(cos(a),sin(a)),n=vec2(-f.y,f.x);"
 "float k0=kblock(q,f,n),kx=kblock(q+vec2(.003,0),f,n),kz=kblock(q+vec2(0,.003),f,n);"
 "kg=-vec2(kx-k0,kz-k0)/.003*.005*s_press*(.35+.65*damp)*(.55+.45*s_new)*(1.-smoothstep(.006,.016,px));}"
 "micro+=(sg*(.8+.2*s_new)+kg)*s_vis;" /* settled soil softens a little, fresh soil is crisp */
 /* dry soil: lips and trench walls crumble into loose grains */
 "micro+=turn((k1.rg-.5)*2.,0.)*.35*s_lip*(1.-damp)*f_big*s_vis;}"
 /* loose soil reads soft: texture grain averaged, fine crumbs; pressed floors smooth */
 "float sl_loose=s_lay*(1.-s_press*s_vis)*(1.-.6*worked);"
 "albedo=mix(albedo,blur/bw,.18*sl_loose);micro+=turn((k2.rg-.5)*2.,-.83)*.16*sl_loose*f_mid;}"
 /* roost clods: lumps on a jittered 11 cm lattice, present where the sim's clod
    density at the lump's own centre beats its random rank; lit as domes with a
    soft contact shadow cast away from the sun. ~2-5 cm, bigger when damp. */
 "float lump=0.,lshade=1.;vec2 lslope=vec2(0);"
 "if(state_on!=0&&s_clod>.004&&f_big>.01){"
 "vec2 ci=floor(p/.11),sh=L.xz/max(L.y,.3);"
 "for(int j=-1;j<=1;j++)for(int i=-1;i<=1;i++){"
 "vec2 id=ci+vec2(i,j);vec3 r=rnd(id);vec2 cw=(id+.15+.7*r.xy)*.11;"
 "if(.001+.999*r.z>textureLod(state,(g+(cw-p)/spacing)/SIDE,0.).a*1.15)continue;"
 "float rad=(.012+.026*fract(r.x*7.31+r.y*3.17))*(.8+.45*damp);vec2 d=p-cw;float t=length(d)/rad;"
 "if(t<1.){float hgt=sqrt(1.-t*t);if(hgt>lump){lump=hgt;lslope=-d/(rad*max(hgt,.25));}}"
 "lshade=min(lshade,mix(.6,1.,smoothstep(.5,1.05,length(p-(cw-sh*rad*.8))/(rad*1.1))));}"
 "if(lump>0.)lshade=1.;lump*=f_big;"
 "micro=mix(micro,lslope*1.3,smoothstep(0.,.25,lump));lshade=mix(1.,lshade,f_big);}"
 "vec3 nb=normalize(vec3(-base_slope.x,1.,-base_slope.y));"
 "vec3 nd=normalize(vec3(-(sharp_slope.x+.3*dslope.x+micro.x),1.,-(sharp_slope.y+.3*dslope.y+micro.y)));"
 /* sun shadows from the deformation only: occlusion along the sun ray over
    current heights minus the same test over base heights. 8 taps, ~3.6 cells. */
 "float shade=1.,lh=length(L.xz);"
 "if(lh>.05&&worked>.003){vec2 sd=(L.xz/lh)/spacing;" /* perf: untouched ground casts no deformation shadow */ "float rise=L.y/lh,stp=.45*min(spacing.x,spacing.y),oc=0.,ob=0.;"
 "for(int i=1;i<=8;i++){float d=stp*float(i),fall=1.-float(i)/10.;vec2 hs=H(g+sd*d);"
 "oc=max(oc,clamp((hs.r-c0.r-rise*d-.01)/.04,0.,1.)*fall);ob=max(ob,clamp((hs.g-c0.g-rise*d-.01)/.04,0.,1.)*fall);}"
 "shade=1.-.36*max(oc-ob,0.);}"
 "float relight=clamp((.65+max(dot(nd,L),0.))/(.65+max(dot(nb,L),0.)),.62,1.45);"
 "float ao=(1.-clamp(hollow*3.,0.,.16)*worked)*(1.-clamp(s_cav*5.,0.,.2)*s_vis);"
 /* damp soil darker and richer; dry crests and old hardpack a little lighter and duller */
 "float lum=dot(albedo,vec3(.299,.587,.114));"
 "float sat=1.+.22*wetv-.20*dryv-.04*firm+.05*s_press*s_vis,val=1.-.18*wetv+.07*dryv+.03*firm*(1.-damp);"
 /* soft layer: pressed trench floors darker; soil lying above the layer top (lips, roost crumbs) is loose
    and dry, so it reads LIGHTER and dustier than packed ground - most while it is FRESH (s_new: the last few
    laps), so the latest passes stand out and the dark ruts stay easy to read against it. A fresh trench
    floor is a touch darker. (Dark loose soil hid the ruts: the whole line went dark.) */
 "val+=(-.07*s_press*(.5+.5*damp)+s_lip*(.06+.10*s_new)*(1.-.5*damp)-.04*s_new*s_press)*s_vis;sat+=(-.06*s_lip*(.4+.6*s_new)+.04*s_new*s_press)*s_vis;"
 "vec3 soilc=max(mix(vec3(lum),albedo,sat),0.)*val;"
 /* sheen: wet rut bottoms and damp hard-pack, never loose dirt or grass */
 "vec3 V=normalize(camera-w),Hv=normalize(L+V);"
 "float gloss=(.06*firm*(.3+.7*damp)+.16*wetv+.05*s_press*s_vis*damp)*(1.-.8*loose)*(1.-green);"
 "float spec=2.*gloss*pow(max(dot(nd,Hv),0.),40.)*max(dot(nd,L),0.);"
 "vec3 sunc=gl_LightSource[0].diffuse.rgb;if(dot(sunc,vec3(1))<.05)sunc=vec3(1);sunc=min(sunc,vec3(1.5));"
 "float sshade=mix(1.,s_shade,s_vis);"
 "vec3 lit=soilc*relight*ao*crevice*shade*lshade*sshade+sunc*spec*shade*sshade;"
 "color=vec4(clamp(mix(native,lit,amount*(1.-.85*green)),0.,1.),1.);}";
#endif
